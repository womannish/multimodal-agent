class CommandRecognition:
    """
    A speech-command recognition system combining Whisper for speech-to-text,
    Kokoro for text-to-speech, and a zero-shot classifier for intent detection.
    It supports wake-word detection, natural command transcription,
    and classification into predefined intents such as 'guard' or 'stay idle'.
    """

    def __init__(self):
        self.commands = ["guard", "stay idle"]
        self.processor = AutoProcessor.from_pretrained("openai/whisper-small")
        self.model = AutoModelForSpeechSeq2Seq.from_pretrained("openai/whisper-small")
        self.tts_pipeline = KPipeline(lang_code='a')
        self.intent_classifier = pipeline("zero-shot-classification", model="facebook/bart-large-mnli")

    def Speechtotext(self, audio_path):
        waveform, sr = torchaudio.load(audio_path)
        if sr != 16000:
            waveform = torchaudio.functional.resample(waveform, sr, 16000)
            sr = 16000
        waveform = waveform.squeeze().numpy()
        inputs = self.processor(waveform, sampling_rate=sr, return_tensors="pt")
        predicted_ids = self.model.generate(**inputs)
        transcription = self.processor.batch_decode(predicted_ids, skip_special_tokens=True)
        return transcription[0].lower()

    def wakeword(self, audio):
        txt = self.Speechtotext(audio)
        if "blueberry" in txt:
            return True
        else:
            return False

    def TexttoSpeech(self, text, voice='af_heart', outfile="output.wav"):
        generator = self.tts_pipeline(text, voice=voice)
        audio_data = None
        sample_rate = 24000
        for result in generator:
            if hasattr(result, "output") and hasattr(result.output, "audio"):
                audio_tensor = result.output.audio
                audio_data = audio_tensor.cpu().numpy()
                break
        if audio_data is not None:
            sf.write(outfile, audio_data, int(sample_rate))
            return outfile
        else:
            raise ValueError("Kokoro pipeline did not yield valid audio data.")

    def commandclassification(self, command):
        """Classify command as 'guard', 'stay idle', or 'unknown'."""
        result = self.intent_classifier(command, candidate_labels=self.commands)
        intent = result["labels"][0]
        confidence = result["scores"][0]
        if confidence < 0.5:
            intent = "unknown"
        return {"intent": intent, "confidence": confidence}

