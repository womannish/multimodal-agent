class LLM:
    """
    A lightweight interface for interacting with Google's Gemini API.
    It initializes a generative language model using a stored API key
    and provides configurable text generation with temperature,
    token limit, and sampling control.
    """

    def __init__(self, model_name="models/gemini-2.5-flash"):
        try:
            self.apikey = userdata.get("GOOGLE_API_KEY")
            if not self.apikey:
                raise ValueError("API key not found in Colab safekeys. Please set GEMINI_API_KEY.")
            genai.configure(api_key=self.apikey)
            self.model = genai.GenerativeModel(model_name)
        except Exception as e:
            print(f"Initialization error: {e}")
            self.model = None

    def generate_text(self, prompt, temperature=0.7, max_tokens=1000, top_p=0.9, top_k=40):
        if not self.model:
            return "Model not initialized properly."

        try:
            response = self.model.generate_content(
                prompt,
                generation_config=genai.types.GenerationConfig(
                    temperature=temperature,
                    max_output_tokens=max_tokens,
                    top_p=top_p,
                    top_k=top_k
                )
            )

            # 🧠 Try to extract text safely from candidates
            text = None
            if hasattr(response, "candidates") and response.candidates:
                for c in response.candidates:
                    if hasattr(c, "content") and hasattr(c.content, "parts"):
                        parts = [p.text for p in c.content.parts if hasattr(p, "text")]
                        if parts:
                            text = "\n".join(parts).strip()
                            break

            # 🔍 Handle blocked / empty responses
            if not text:
                finish_reason = getattr(response.candidates[0], "finish_reason", "unknown")
                feedback = getattr(response, "prompt_feedback", None)
                return f"[No usable text returned] finish_reason={finish_reason}, feedback={feedback}"

            return text

        except Exception as e:
            return f"API error: {e}"

