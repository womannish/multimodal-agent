def run_guard_system():
    state = GuardState()
    current_state = "Idle"

    print("[SYSTEM] AI Guard initialized. Starting in Idle mode...")

    while True:
        if current_state == "Idle":
            print("[STATE] Idle: Waiting for wakeword...")
            state, signal = idle_state(state)
            if signal == "wakeword_detected":
                print("[EVENT] Wakeword detected! Moving to Listening...")
                current_state = "Listening"

        elif current_state == "Listening":
            print("[STATE] Listening: Waiting for command...")
            state, signal = listening_state(state)

            if signal == "activate_guard":
                print("[EVENT] Activating Guard Mode.")
                current_state = "GuardMode"

            elif signal == "deactivate_guard":
                print("[EVENT] Command to stay idle received.")
                current_state = "Idle"

            elif signal == "unknown_command":
                print("[EVENT] Unknown command. Returning to Idle.")
                current_state = "Idle"

        elif current_state == "GuardMode":
            print("[STATE] Guard Mode: Monitoring environment...")
            frame = capture_webcam_frame()

            # Wakeword interrupt check (always available)
            audio = get_audio_input()
            if command_recognition.wakeword(audio):
                print("[INTERRUPT] Wakeword detected! Switching to Listening mode.")
                current_state = "Listening"
                continue

            # Face recognition loop
            face_path = save_temp_frame(frame)
            if not face_recognition.is_trusted(face_path):
                print("[EVENT] Unrecognized face detected! Escalating.")
                state.is_trusted = False
                state.escalation_level += 1
                current_state = "Speaking"
            else:
                state.is_trusted = True
                state.escalation_level = 0
                print("[STATUS] Trusted individual confirmed.")
                # Continue staying in guard mode

        elif current_state == "Speaking":
            print("[STATE] Speaking: Responding to potential intruder...")
            state, signal = speaking_state(state)

            if signal == "back_to_guarding":
                print("[EVENT] Response complete. Returning to Guard Mode.")
                current_state = "GuardMode"

        else:
            print(f"[ERROR] Unknown state encountered: {current_state}")
            current_state = "Idle"

run_guard_system()

