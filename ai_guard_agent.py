def load_trusted_embeddings(embeddings_dir):
    """
    Loads all .pt embeddings from a given directory (e.g. Google Drive folder)
    and returns a single tensor of shape [N, D] for FaceRecognition.
    """
    embeddings = []
    for emb_path in Path(embeddings_dir).glob("*.pt"):
        try:
            emb = torch.load(emb_path, map_location="cpu")
            embeddings.append(emb)
            print(f"Loaded: {emb_path.name}")
        except Exception as e:
            print(f"Skipping {emb_path.name}: {e}")

    if not embeddings:
        raise ValueError("No valid embeddings found in the directory.")

    # Stack into a single tensor [N, D]
    trusted_tensor = torch.stack(embeddings)
    return trusted_tensor

