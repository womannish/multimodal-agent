def idle_state(state: GuardState):
    audio = get_audio_input()
    detected = command_recognition.wakeword(audio)
    if detected:
        state.mode = "Listening"
        return state, "wakeword_detected"
    return state, "stay_idle"

def listening_state(state: GuardState):
    audio = get_audio_input()
    command = command_recognition.Speechtotext(audio)
    state.last_command = command.lower()
    detected_command = command_recognition.commandclassification(command)

    intent = detected_command["intent"]
    if intent == "unknown":
        return state, "unknown_command"
    elif intent == "guard":
        state.mode = "GuardMode"
        return state, "activate_guard"
    elif intent == "stay idle":
        state.mode = "Idle"
        return state, "deactivate_guard"

def guard_mode_state(state: GuardState):
    frame = capture_webcam_frame()
    face_path = save_temp_frame(frame)
    if not face_recognition.is_trusted(face_path):
        state.escalation_level += 1
        state.is_trusted = False
        state.mode = "Speaking"
        return state, "intruder_detected"
    else:
        state.is_trusted = True
        return state, "trusted_person"

def speaking_state(state: GuardState):
    if not state.is_trusted:
        level_prompts = [
            "Who are you? This room is restricted.",
            "You are not recognized. Please identify yourself.",
            "This is a final warning. Leave immediately, or I will raise an alarm."
        ]
        state.escalation_level = min(state.escalation_level, 3)
        prompt = level_prompts[state.escalation_level - 1]
        response = generate_guard_response(prompt)
        outfile = command_recognition.TexttoSpeech(response)
        play_audio(outfile)

    state.mode = "GuardMode"
    return state, "back_to_guarding"

