class FaceRecognition:
    """
    A facial verification utility using DeepFace and PyTorch.
    It extracts facial embeddings, normalizes them, and verifies
    if a detected face matches any of the trusted individuals
    based on cosine similarity.
    """

    def __init__(self, trusted_individuals):
        self.trusted_individuals = torch.nn.functional.normalize(
            torch.tensor(trusted_individuals, dtype=torch.float32), p=2, dim=1
        )

    @staticmethod
    def get_embedding(path, detectionmodel="retinaface", recognitionmodel="VGG-Face", show_face=False):
        # Try normal detection first
        try:
            detections = DeepFace.extract_faces(
                img_path=path,
                detector_backend=detectionmodel,
                enforce_detection=True,
                align=True
            )
        except ValueError:
            # Fallback: allow no strict detection
            print("[Warning] No face detected strictly — retrying with enforce_detection=False")
            detections = DeepFace.extract_faces(
                img_path=path,
                detector_backend=detectionmodel,
                enforce_detection=False,
                align=True
            )

        if not detections:
            raise ValueError("No face detected in the image (even after fallback).")

        cropped_face = detections[0]["face"]
        rep = DeepFace.represent(
            img_path=cropped_face,
            model_name=recognitionmodel,
            enforce_detection=False
        )[0]["embedding"]

        emb = torch.tensor(rep, dtype=torch.float32)
        emb = torch.nn.functional.normalize(emb, p=2, dim=0)

        return emb

    @staticmethod
    def cosine_similarity(emb1, emb2):
        return torch.cosine_similarity(emb1.unsqueeze(0), emb2.unsqueeze(0))

    def is_trusted(self, path, detectionmodel="retinaface", recognitionmodel="VGG-Face", show_face=False, threshold=0.5):
        emb = self.get_embedding(path, detectionmodel, recognitionmodel, show_face)
        similarities = torch.cosine_similarity(emb.unsqueeze(0), self.trusted_individuals)
        return torch.any(similarities > threshold).item()

def save_image_embeddings(image_dir, output_dir="embeddings",
                          detectionmodel="retinaface", recognitionmodel="VGG-Face"):
    """
    Computes and stores facial embeddings for all .jpg images in a directory.
    Each image is processed through the FaceRecognition pipeline using the
    specified detection and recognition models, and the resulting normalized
    embeddings are saved as .pt files in the output directory.
    """
    os.makedirs(output_dir, exist_ok=True)
    fr = FaceRecognition(trusted_individuals=torch.empty(0, 512))
    for img_path in Path(image_dir).glob("*.jpg"):
        try:
            emb = fr.get_embedding(str(img_path), detectionmodel=detectionmodel, recognitionmodel=recognitionmodel)
            save_path = Path(output_dir) / f"{img_path.stem}_embedding.pt"
            torch.save(emb, save_path)
            print(f"Saved embedding for {img_path.name} → {save_path}")
        except Exception as e:
            print(f"Skipping {img_path.name}: {e}")

