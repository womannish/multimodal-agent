memory = ConversationBufferMemory(return_messages=True)

def generate_guard_response(prompt):
    history = memory.load_memory_variables({})["history"]
    full_prompt = (
        "You are an AI security guard protecting a private room. "
        "Be firm, professional, and escalate gradually with unrecognized visitors.\n\n"
        "Conversation so far:\n" + str(history) + "\nUser: " + prompt
    )
    response = llm.generate_text(full_prompt)
    memory.save_context({"input": prompt}, {"output": response})
    return response

